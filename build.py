#!/usr/bin/env python3
"""Generate the 42vibes Firefox themes (dark and light).

Everything under ``firefox/`` is generated by this script:

* ``firefox/42vibes-<mode>/manifest.json``
* ``firefox/42vibes-<mode>/icons/icon-{48,96,128}.png``

Colors come from ``vendor/palette.json`` (semantic roles, plus ``ansi.green``
for the icon glyph). The output is deterministic: no timestamps, stable key
order, and PNG metadata chunks are dropped, so two runs produce byte-identical
files.

``--out DIR`` writes the same tree below DIR instead of ``firefox/``. That is
how ``validate.py`` builds into throw-away directories without touching the
checked-in artifacts.

Icons are rasterized with ImageMagick (``magick`` or ``convert``). If neither
is installed, icon rendering is skipped: with the default output the committed
PNGs stay untouched, with ``--out`` no icons are written at all. Either way a
warning is printed and the caller must not claim rendered icons.
"""

from __future__ import annotations

import argparse
import json
import shutil
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PALETTE_PATH = ROOT / "vendor" / "palette.json"
THEME_ROOT = ROOT / "firefox"

THEME_VERSION = "0.1.0"
MODES = ("dark", "light")
ICON_SIZES = (48, 96, 128)

# Explicit Gecko IDs make the themes identifiable for permanent unsigned
# self-installation on ESR; the two variants must never share an ID.
GECKO_IDS = {
    "dark": "42vibes-dark@42vibes.local",
    "light": "42vibes-light@42vibes.local",
}
GECKO_STRICT_MIN_VERSION = "115.0"

DESCRIPTIONS = {
    "dark": (
        "Dark theme for Firefox built from the 42vibes palette: deep petrol-navy "
        "frame, soft blue-grey text and teal accents."
    ),
    "light": (
        "Light theme for Firefox built from the 42vibes palette: soft blue-grey "
        "surfaces, near-black text and deep teal accents."
    ),
}

# Theme color role -> palette path ("semantic.bg", "ansi.black", ...).
# The roles on the left are the required Firefox theme keys; validate.py
# resolves the same palette paths independently.
ROLE_MAP = {
    "frame": "semantic.bg",
    "frame_inactive": "semantic.bg_deep",
    "tab_background_text": "semantic.text_muted",
    "tab_text": "semantic.text",
    "tab_selected": "semantic.surface_high",
    "tab_line": "semantic.accent",
    "toolbar": "semantic.surface",
    "toolbar_text": "semantic.text",
    "toolbar_field": "semantic.surface",
    "toolbar_field_text": "semantic.text",
    "toolbar_field_border": "semantic.border_strong",
    "toolbar_field_focus": "semantic.surface_high",
    "toolbar_top_separator": "semantic.bg_deep",
    "toolbar_bottom_separator": "semantic.bg_deep",
    "popup": "semantic.surface",
    "popup_text": "semantic.text",
    "popup_border": "semantic.border",
    "popup_highlight": "semantic.surface_selected",
    "popup_highlight_text": "semantic.text",
    "sidebar": "semantic.surface",
    "sidebar_text": "semantic.text_muted",
    "sidebar_border": "semantic.border",
    "button_background_hover": "semantic.surface_high",
    "icons": "semantic.text_muted",
    "ntp_background": "semantic.bg",
    "ntp_text": "semantic.text",
}

# Icon colors: backplate and outline from semantic roles, glyph in ansi.green
# (petrol), which matches semantic.accent in both modes.
ICON_COLORS = {
    "dark": {
        "backplate": "semantic.bg",
        "outline": "semantic.border",
        "glyph": "ansi.green",
    },
    "light": {
        "backplate": "semantic.surface_high",
        "outline": "semantic.border",
        "glyph": "ansi.green",
    },
}

# 5x7 pixel glyphs, rendered as merged blocks. No font is involved, so the
# rendering does not depend on installed fonts.
GLYPHS = {
    "4": (
        "...#.",
        "..#..",
        ".#...",
        "#....",
        "#####",
        "...#.",
        "...#.",
    ),
    "2": (
        ".###.",
        "#...#",
        "....#",
        "...#.",
        "..#..",
        ".#...",
        "#####",
    ),
}

CELL = 10
DIGIT_GAP = 10
TEXT = "42"


def palette_value(palette: dict, mode: str, path: str) -> str:
    """Resolve "semantic.bg" against palette[mode] and return "#rrggbb"."""
    group, name = path.split(".", 1)
    try:
        value = palette[mode][group][name]
    except KeyError as exc:  # pragma: no cover - palette is validated first
        raise SystemExit(f"palette: missing {mode}.{group}.{name}") from exc
    return value


# Roles that are derived locally instead of being palette tokens: a boundary
# and a selection surface that need more contrast than the base roles provide.
# (base path, blend path, weight per mode)
DERIVED_ROLES = {
    "semantic.border_strong": ("semantic.border", "semantic.interactive", {"dark": 0.40, "light": 0.70}),
    "semantic.surface_selected": ("semantic.surface_high", "semantic.interactive", {"dark": 0.55, "light": 0.80}),
}


def blend(first: str, second: str, weight: float) -> str:
    """Linear RGB blend of two #rrggbb colors, weight applied to second."""
    a = [int(first.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4)]
    b = [int(second.lstrip("#")[i : i + 2], 16) for i in (0, 2, 4)]
    return "#" + "".join(
        f"{round(x + (y - x) * weight):02x}" for x, y in zip(a, b)
    )


def theme_colors(palette: dict, mode: str) -> dict:
    colors = {}
    for role, path in ROLE_MAP.items():
        if path in DERIVED_ROLES:
            base, other, weights = DERIVED_ROLES[path]
            colors[role] = blend(
                palette_value(palette, mode, base),
                palette_value(palette, mode, other),
                weights[mode],
            )
        else:
            colors[role] = palette_value(palette, mode, path)
    return colors


def manifest(palette: dict, mode: str) -> dict:
    return {
        "manifest_version": 2,
        "name": f"42vibes {'Dark' if mode == 'dark' else 'Light'}",
        "version": THEME_VERSION,
        "description": DESCRIPTIONS[mode],
        "browser_specific_settings": {
            "gecko": {
                "id": GECKO_IDS[mode],
                "strict_min_version": GECKO_STRICT_MIN_VERSION,
            }
        },
        "icons": {str(size): f"icons/icon-{size}.png" for size in ICON_SIZES},
        "theme": {
            "colors": theme_colors(palette, mode),
            "properties": {"color_scheme": mode},
        },
    }


def icon_svg(palette: dict, mode: str) -> str:
    colors = {
        role: palette_value(palette, mode, path)
        for role, path in ICON_COLORS[mode].items()
    }
    glyphs = list(TEXT)
    total_width = len(glyphs) * len(GLYPHS["4"][0]) * CELL + (len(glyphs) - 1) * DIGIT_GAP
    origin_x = (128 - total_width) // 2
    origin_y = (128 - len(GLYPHS["4"]) * CELL) // 2

    blocks = []
    for index, char in enumerate(glyphs):
        bitmap = GLYPHS[char]
        offset_x = origin_x + index * (len(bitmap[0]) * CELL + DIGIT_GAP)
        for row, line in enumerate(bitmap):
            for column, cell in enumerate(line):
                if cell == "#":
                    blocks.append(
                        f'    <rect x="{offset_x + column * CELL}" '
                        f'y="{origin_y + row * CELL}" '
                        f'width="{CELL}" height="{CELL}"/>'
                    )

    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" '
        'viewBox="0 0 128 128" role="img" aria-label="42vibes">\n'
        f'  <rect x="1" y="1" width="126" height="126" rx="27" ry="27" '
        f'fill="{colors["backplate"]}" stroke="{colors["outline"]}" '
        'stroke-width="2"/>\n'
        f'  <g fill="{colors["glyph"]}">\n'
        + "\n".join(blocks)
        + "\n  </g>\n</svg>\n"
    )


def find_renderer() -> str | None:
    for candidate in ("magick", "convert"):
        found = shutil.which(candidate)
        if found:
            return found
    return None


def strip_png_metadata(raw: bytes) -> bytes:
    """Keep only critical PNG chunks so repeated builds are byte-identical."""
    if raw[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("renderer did not produce a PNG")
    keep = {b"IHDR", b"PLTE", b"tRNS", b"IDAT", b"IEND"}
    out = bytearray(raw[:8])
    offset = 8
    while offset < len(raw):
        length = struct.unpack(">I", raw[offset : offset + 4])[0]
        kind = raw[offset + 4 : offset + 8]
        if kind in keep:
            out += raw[offset : offset + length + 12]
        offset += length + 12
    if b"IEND" not in out:  # pragma: no cover - defensive
        raise ValueError("PNG is missing IEND")
    return bytes(out)


def display(path: Path) -> str:
    """Path relative to the repository when possible, absolute otherwise."""
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def render_icons(palette: dict, mode: str, icon_dir: Path, renderer: str | None) -> bool:
    """Render icons into *icon_dir*. Returns False when ImageMagick is absent."""
    if renderer is None:
        print(
            "warning: ImageMagick (magick/convert) not found; "
            f"icon rendering skipped for {display(icon_dir)}"
            + (
                " (committed PNGs left untouched)"
                if ROOT in icon_dir.parents
                else " (no icons written)"
            ),
            file=sys.stderr,
        )
        return False

    svg = icon_svg(palette, mode).encode("utf-8")
    icon_dir.mkdir(parents=True, exist_ok=True)
    for size in ICON_SIZES:
        result = subprocess.run(
            [
                renderer,
                "-background",
                "none",
                "svg:-",
                "-resize",
                f"{size}x{size}",
                "-depth",
                "8",
                "png:-",
            ],
            input=svg,
            capture_output=True,
            check=False,
        )
        if result.returncode != 0:
            raise SystemExit(
                f"icon rendering failed for {mode} {size}px: "
                + result.stderr.decode("utf-8", "replace").strip()
            )
        png = strip_png_metadata(result.stdout)
        (icon_dir / f"icon-{size}.png").write_bytes(png)
    return True


def write_json(path: Path, payload: dict) -> None:
    text = json.dumps(payload, indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8")


def build(out_root: Path) -> int:
    palette = json.loads(PALETTE_PATH.read_text(encoding="utf-8"))
    renderer = find_renderer()
    rendered = False

    for mode in MODES:
        theme_dir = out_root / f"42vibes-{mode}"
        theme_dir.mkdir(parents=True, exist_ok=True)
        write_json(theme_dir / "manifest.json", manifest(palette, mode))
        rendered = render_icons(palette, mode, theme_dir / "icons", renderer) or rendered

    print(f"build: wrote 2 manifests under {display(out_root)}")
    if rendered:
        print(f"build: rendered icons {', '.join(str(size) for size in ICON_SIZES)} px")
    else:
        print("build: icons skipped (no ImageMagick)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--out",
        type=Path,
        default=THEME_ROOT,
        metavar="DIR",
        help="write the theme tree below DIR instead of firefox/",
    )
    args = parser.parse_args(argv)
    return build(args.out)


if __name__ == "__main__":
    sys.exit(main())
